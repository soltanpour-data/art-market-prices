"""
Step 0 — Fetch the real London auction data.

Downloads the cleaned `sales` data set from the public research repository
mdlincoln/londonauctions (Matthew Lincoln & Abram Fox, "The Temporal
Dimensions of the London Art Auction, 1780-1835", British Art Studies, 2016;
data originally from the Getty Provenance Index) and converts it from R's
.rda format to CSV.

The raw file is ~5 MB; the converted CSV (~40 MB, 304,788 transactions) is
written to data/ but intentionally NOT committed to git — it is regenerated
by this script (see .gitignore). Re-running skips the download unless
--force is passed.

Output: data/raw_london_auctions.csv  (gitignored)
"""

import sys
import urllib.request
from pathlib import Path

RDA_URL = ("https://github.com/mdlincoln/londonauctions"
           "/raw/master/data/sales.rda")
RDA_PATH = Path("data/sales.rda")
CSV_PATH = Path("data/raw_london_auctions.csv")
EXPECTED_ROWS = 304788

force = "--force" in sys.argv

if not RDA_PATH.exists() or force:
    print(f"Downloading {RDA_URL} ...")
    urllib.request.urlretrieve(RDA_URL, RDA_PATH)
    print(f"Saved {RDA_PATH} ({RDA_PATH.stat().st_size / 1e6:.1f} MB)")
else:
    print(f"Using cached {RDA_PATH} (pass --force to re-download)")

try:
    import pyreadr
except ImportError:
    sys.exit("pyreadr is required: pip install -r requirements.txt")

print("Converting sales.rda -> CSV ...")
df = pyreadr.read_r(str(RDA_PATH))["sales"]
df.to_csv(CSV_PATH, index=False)

n = len(df)
print(f"Rows: {n:,} (expected ~{EXPECTED_ROWS:,}) | Columns: {len(df.columns)}")
print(f"Year range: {df['year'].min()}-{df['year'].max()}")
assert abs(n - EXPECTED_ROWS) < 5000, "Row count differs wildly from expected!"
print(f"\nSaved to {CSV_PATH} (gitignored — regenerated by this script)")
